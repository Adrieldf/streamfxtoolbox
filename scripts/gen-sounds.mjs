// Lists the audio files in public/sounds for the effects' sound pickers.
// Runs before `npm run dev` and `npm run build`; run `npm run sounds` after
// adding files while the dev server is already running.
import { readdirSync, writeFileSync } from "node:fs";

// Formats Chromium (and so OBS) can play. AIFF is not one of them.
const PLAYABLE = /\.(wav|mp3|ogg|flac|m4a|webm)$/i;
const AUDIO = /\.(wav|mp3|ogg|flac|m4a|webm|aiff?|wma)$/i;

const files = readdirSync("public/sounds").sort();
const sounds = [];
const used = new Set();

for (const file of files) {
  if (!AUDIO.test(file)) continue;
  if (!PLAYABLE.test(file)) {
    console.warn(`sounds: skipping ${file} (browsers cannot play this format)`);
    continue;
  }
  // Freesound names look like "12345__uploader__the-name.wav"; keep the name
  const name = file.replace(/\.[^.]+$/, "").replace(/^\d+__.+?__/, "");
  const base = name.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
  let id = base;
  for (let n = 2; used.has(id); n++) id = `${base}-${n}`;
  used.add(id);
  const label = base.replace(/-/g, " ").replace(/^./, (c) => c.toUpperCase());
  sounds.push({ id, label, file });
}

writeFileSync(
  "effects/soundLibrary.generated.ts",
  `// Generated by scripts/gen-sounds.mjs from public/sounds. Do not edit.
export const soundLibrary: { id: string; label: string; file: string }[] = ${JSON.stringify(sounds, null, 2)};
`,
);
console.log(`sounds: ${sounds.length} listed`);
